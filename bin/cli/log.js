const { internalLogFile } = require('./paths');
const { appendLine, utcDateKey } = require('./util');

function writeInternalLog(cfg, action, data = {}) {
  const now = new Date();
  try {
    appendLine(internalLogFile(cfg, utcDateKey(now)), JSON.stringify({
      ts: now.toISOString(),
      action,
      ...data,
    }));
  } catch {
    // Internal logs are best-effort and must never break hooks.
  }
}

function errorDetails(err) {
  return {
    message: err && err.message ? err.message : String(err),
    stack: err && err.stack ? String(err.stack) : '',
  };
}

module.exports = {
  errorDetails,
  writeInternalLog,
};
